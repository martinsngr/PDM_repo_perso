"""Free-surface part and porous-wall coupling on the vertical slit: tables and figure from the existing runs.

    ../../.venv/bin/python slitVerification.py

Reads the run folders in ../../meshing_strat_trial/slit_test/ (no new runs) and writes summary.md and
slit_verification.png in this folder. What is compared (see README.md):
  1. real walls (S0_*, constantAlphaContactAngle) vs the analytical slit rise (Bosanquet, from the 0.1 mm column);
  2. stock interFoam (IF_fill_total) vs our solver on the same real-wall slit (gap 8, theta 60);
  3. impermeable porous walls (P_*_K1e-20, G + H + F' + I) vs real walls, 5 configurations;
  4. permeable porous walls (K 1e-20 / 1e-14 / 1e-11, gap 8, theta 60): ordering of the gap rise;
  5. mesh: 10 um (P_dx10_w16_t60_K1e-11) vs 20 um (P_w8_t60_K1e-11), same geometry and properties.
Measures (as slit_test/slitReport.py and benchSlit.py): gap meniscus h = first x where the gap-averaged alpha drops
below 0.5, linear interpolation between the two cells; wall front = first x where the wall-averaged alpha < 0.1;
max |U| over the cells. All runs are 2 mm long, inlet at x = 0, 0.1 mm initial water column in the gap.
"""
import os
import re
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SLIT = os.path.join(HERE, "..", "..", "meshing_strat_trial", "slit_test")
sys.path.insert(0, SLIT)
sys.path.insert(0, os.path.join(SLIT, "..", "tools"))
from initFields import read_internal  # noqa: E402
from slitReport import CAT, GRID, INK, MUTED, analytic, readU  # noqa: E402

LX = 2e-3
CONFIGS = [(4, 60), (8, 60), (15, 60), (8, 40), (8, 80)]  # gap cells, theta
RAMP_K = ["#6da7ec", "#2a78d6", "#184f95"]                # sequential blue (dataviz reference ramp 300/450/600)


def info(c):
    d = dict(l.split(None, 1) for l in open(os.path.join(SLIT, c, "slit.info")) if l.strip())
    return {k: v.strip() for k, v in d.items()}


def series(c):
    """(t, meniscus h, wall front, max |U|) per written time of run c."""
    d = info(c)
    w, nw, nz = int(d["w"]), int(d["NW"]), int(d["nz"])
    dx = float(d.get("dx", 20e-6))
    nx = round(LX / dx)
    x = (np.arange(nx) + 0.5) * dx
    path = os.path.join(SLIT, c)
    name = "alpha.water" if d.get("solver") == "interFoam" else "alpha.wetting"
    out = []
    for t in sorted((t for t in os.listdir(path) if re.fullmatch(r"[0-9.e+-]+", t)), key=float):
        a = np.array(read_internal(os.path.join(path, t, name), nx * nz)).reshape(nz, nx)
        g = a[nw:nw + w].mean(axis=0)
        i = np.where(g < 0.5)[0]
        if not len(i):
            h = LX
        elif i[0] == 0:
            h = 0.0
        else:
            i = i[0]
            h = x[i - 1] + (g[i - 1] - 0.5) / (g[i - 1] - g[i]) * dx
        wf = np.nan
        if nw:
            j = np.where(np.concatenate([a[:nw], a[nw + w:]]).mean(axis=0) < 0.1)[0]
            wf = x[j[0]] if len(j) else LX
        out.append((float(t), h, wf, readU(os.path.join(path, t, "U"))))
    return np.array(out)


def at(s, t, col=1):
    return s[np.argmin(abs(s[:, 0] - t)), col]


def main():
    S = {}
    for w, th in CONFIGS:
        S[f"S0_w{w}_t{th}"] = series(f"S0_w{w}_t{th}")
        S[f"P_w{w}_t{th}_K1e-20"] = series(f"P_w{w}_t{th}_K1e-20")
    for c in ["IF_fill_total", "P_w8_t60_K1e-14", "P_w8_t60_K1e-11", "P_dx10_w16_t60_K1e-11"]:
        S[c] = series(c)
    B = {(w, th): analytic(w * 20e-6, th, T=LX) for w, th in CONFIGS}

    L = ["# Slit verification: free surface and porous walls", "",
         "Generated by `slitVerification.py` from the runs in `meshing_strat_trial/slit_test/` (see README.md).", "",
         "## 1-3. Gap meniscus: real walls vs Bosanquet, interFoam vs real walls, porous K 1e-20 vs real walls", "",
         "| gap [cells] | θ | t [ms] | Bosanquet [mm] | real walls S0 [mm] (vs Bosanquet) | porous K 1e-20 P [mm] (vs S0) "
         "| max \\|U\\| S0 / P [m/s] |", "|---|---|---|---|---|---|---|"]
    worst_p, worst_b = 0.0, (np.inf, -np.inf)
    for w, th in CONFIGS:
        s0, p = S[f"S0_w{w}_t{th}"], S[f"P_w{w}_t{th}_K1e-20"]
        tb, hb = B[(w, th)]
        for t in (1e-3, 2e-3):
            hs, hp, hbos = at(s0, t), at(p, t), np.interp(t, tb, hb)
            eb, ep = (hs / hbos - 1) * 100, (hp / hs - 1) * 100
            worst_p = max(worst_p, abs(ep))
            worst_b = (min(worst_b[0], eb), max(worst_b[1], eb))
            L.append(f"| {w} | {th}° | {t * 1e3:.0f} | {hbos * 1e3:.3f} | {hs * 1e3:.3f} ({eb:+.1f} %) | "
                     f"{hp * 1e3:.3f} ({ep:+.1f} %) | {s0[:, 3].max():.2f} / {p[:, 3].max():.2f} |")
    s0, fi = S["S0_w8_t60"], S["IF_fill_total"]
    dif = max(abs(at(fi, t) - at(s0, t)) for t in (5e-4, 1e-3, 1.5e-3, 2e-3))
    L += ["", f"- Real walls vs Bosanquet: {worst_b[0]:+.1f} to {worst_b[1]:+.1f} % (always fast).",
          f"- Porous K 1e-20 vs real walls: max |difference| {worst_p:.1f} % → **{'pass' if worst_p <= 2 else 'FAIL'}** "
          "(criterion ≤ 2 %).",
          f"- Stock interFoam vs our solver, real walls gap 8 θ 60° (0.5/1/1.5/2 ms): max |Δh| {dif * 1e3:.3f} mm → "
          f"**{'pass' if dif <= 0.01e-3 + 1e-12 else 'FAIL'}** (criterion ≤ 0.01 mm).", ""]

    L += ["## 4. Permeable walls (gap 8, θ 60°, 20 µm)", "",
          "| K walls [m²] | h 1 ms [mm] | h 2 ms [mm] | wall front 2 ms [mm] | max \\|U\\| [m/s] |", "|---|---|---|---|---|"]
    perm = [("1e-20", S["P_w8_t60_K1e-20"]), ("1e-14", S["P_w8_t60_K1e-14"]), ("1e-11", S["P_w8_t60_K1e-11"])]
    for k, s in perm:
        L.append(f"| {k} | {at(s, 1e-3) * 1e3:.3f} | {at(s, 2e-3) * 1e3:.3f} | {at(s, 2e-3, 2) * 1e3:.3f} | "
                 f"{s[:, 3].max():.2f} |")
    hs = [at(s, 2e-3) for _, s in perm]
    mono = hs[0] >= hs[1] >= hs[2]
    L += ["", f"- Gap rise decreases with wall permeability → **{'pass' if mono else 'FAIL'}** (ordering only; "
          "how much water the walls take is not validated).", ""]

    a, b = S["P_w8_t60_K1e-11"], S["P_dx10_w16_t60_K1e-11"]
    L += ["## 5. Mesh: 20 µm vs 10 µm (gap 160 µm, walls 160 µm, K 1e-11, θ 60°; 10 µm with `darcyFaceMaxDa 0.5`)", "",
          "| t [ms] | h 20 µm [mm] | h 10 µm [mm] | Δ | wall front 20 µm [mm] | 10 µm [mm] | Δ |", "|---|---|---|---|---|---|---|"]
    for t in (5e-4, 1e-3, 1.5e-3, 2e-3):
        h2, h1, f2, f1 = at(a, t), at(b, t), at(a, t, 2), at(b, t, 2)
        L.append(f"| {t * 1e3:.1f} | {h2 * 1e3:.3f} | {h1 * 1e3:.3f} | {(h2 / h1 - 1) * 100:+.1f} % | "
                 f"{f2 * 1e3:.3f} | {f1 * 1e3:.3f} | {(f2 / f1 - 1) * 100:+.1f} % |")
    L += ["", "- Two meshes only: a trend, not a convergence order. The 10 µm wall is 16 cells, so its wall-front "
          "resolution differs too.", ""]
    open(os.path.join(HERE, "summary.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))

    # figure: row 1 = the 5 configurations (meniscus vs t), row 2 = permeability and mesh
    fig, ax = plt.subplots(2, 5, figsize=(15, 6.2), constrained_layout=True)
    for k, (w, th) in enumerate(CONFIGS):
        A = ax[0, k]
        tb, hb = B[(w, th)]
        A.plot(tb * 1e3, hb * 1e3, color=INK, lw=1.5, ls="--", label="Bosanquet (analytical)")
        s0, p = S[f"S0_w{w}_t{th}"], S[f"P_w{w}_t{th}_K1e-20"]
        A.plot(s0[:, 0] * 1e3, s0[:, 1] * 1e3, color=CAT[0], lw=2, label="real walls (S0)")
        A.plot(p[:, 0] * 1e3, p[:, 1] * 1e3, color=CAT[1], lw=2, ls=(0, (4, 2)), label="porous walls K 1e-20 (P)")
        if (w, th) == (8, 60):
            A.plot(fi[:, 0] * 1e3, fi[:, 1] * 1e3, color=CAT[2], lw=2, ls=":", label="stock interFoam, real walls")
        A.set_title(f"gap {w} cells ({w * 20} µm), θ {th}°", color=INK)
        A.set(xlabel="t [ms]", ylabel="gap meniscus h [mm]" if k == 0 else None, xlim=(0, 2), ylim=(0, 2))
    h, l = ax[0, 1].get_legend_handles_labels()
    ax[0, 0].legend(h, l, frameon=False, fontsize=8, loc="upper left")
    A = ax[1, 0]
    for (k, s), col in zip(perm, RAMP_K):
        A.plot(s[:, 0] * 1e3, s[:, 1] * 1e3, color=col, lw=2, label=f"K {k} m²")
    A.set(title="Permeable walls: gap meniscus", xlabel="t [ms]", ylabel="gap meniscus h [mm]", xlim=(0, 2), ylim=(0, 2))
    A.legend(frameon=False, fontsize=8, loc="upper left")
    A = ax[1, 1]
    for s, col, lab in [(a, CAT[0], "20 µm"), (b, CAT[1], "10 µm")]:
        A.plot(s[:, 0] * 1e3, s[:, 1] * 1e3, color=col, lw=2, label=f"{lab}: gap meniscus")
        A.plot(s[:, 0] * 1e3, s[:, 2] * 1e3, color=col, lw=2, ls=(0, (4, 2)), label=f"{lab}: wall front")
    A.set(title="Mesh, K 1e-11 walls", xlabel="t [ms]", ylabel="position [mm]", xlim=(0, 2), ylim=(0, 2))
    A.legend(frameon=False, fontsize=8, loc="upper left")
    A = ax[1, 2]
    errs_b = [[(at(S[f"S0_w{w}_t{th}"], t) / np.interp(t, *B[(w, th)]) - 1) * 100 for w, th in CONFIGS] for t in (1e-3, 2e-3)]
    errs_p = [[(at(S[f"P_w{w}_t{th}_K1e-20"], t) / at(S[f"S0_w{w}_t{th}"], t) - 1) * 100 for w, th in CONFIGS]
              for t in (1e-3, 2e-3)]
    xs = np.arange(len(CONFIGS))
    A.bar(xs - 0.2, errs_b[1], 0.36, color=CAT[0], label="real walls vs Bosanquet, 2 ms")
    A.bar(xs + 0.2, errs_p[1], 0.36, color=CAT[1], label="porous K 1e-20 vs real walls, 2 ms")
    A.axhline(0, color=MUTED, lw=0.8)
    A.set_xticks(xs, [f"{w}c\n{th}°" for w, th in CONFIGS])
    A.set(title="Relative difference at 2 ms", ylabel="%", ylim=(-1, 15))
    A.legend(frameon=False, fontsize=8, loc="upper right")
    for A in ax[1, 3:]:
        A.axis("off")
    ax[1, 3].text(0, 0.95, "Not shown here (not validated):\n• how much water the walls take from the gap\n"
                  "• the interface pressure jump\n• θ on wet wall surfaces (biased low)\n\n"
                  "Runs: meshing_strat_trial/slit_test/\nScript: verification/slit_freeSurface/",
                  va="top", fontsize=8.5, color=MUTED, transform=ax[1, 3].transAxes)
    for A in ax.flat:
        A.grid(color=GRID, lw=0.6)
        for sp in ("top", "right"):
            A.spines[sp].set_visible(False)
    fig.savefig(os.path.join(HERE, "slit_verification.png"), dpi=150)
    print("slit_verification.png written")


if __name__ == "__main__":
    main()
